/**
 * Generates Amplience content-type TypeScript definitions from exported JSON schemas.
 *
 * Resolves local schema $id references and vendors the Amplience core schema so
 * json-schema-to-typescript can produce property-level types instead of `[k: string]: unknown`.
 */

import fs from 'fs'
import path from 'path'
import { fileURLToPath } from 'url'
import $RefParser from '@apidevtools/json-schema-ref-parser'
import { compile } from 'json-schema-to-typescript'
import prettier from 'prettier'

const scriptDir = path.dirname(fileURLToPath(import.meta.url))
const root = path.resolve(scriptDir, '..')
const schemasDir = path.join(
  root,
  '.scayle/cms/contentModel/amplience/schemas/schemas',
)
const vendorCore = path.join(
  root,
  '.scayle/cms/contentModel/amplience/schemas/vendor/bigcontent-core.json',
)
const outDir = path.join(root, 'modules/cms/providers/amplience/types/gen')

let prettierConfig

/**
 * Formats TypeScript with the boilerplate Prettier config and writes it to disk.
 *
 * The resolved config is cached on first use so every generated file reuses it.
 *
 * @param filepath - Absolute output path, also used to pick the Prettier parser
 * @param content - TypeScript source to format and write
 */
const writeFormattedFile = async (filepath, content) => {
  prettierConfig ??= await prettier.resolveConfig(filepath, {
    editorconfig: true,
  })

  fs.writeFileSync(
    filepath,
    await prettier.format(content, { ...prettierConfig, filepath }),
  )
}

const BANNER = `/* eslint-disable */
/**
 * This file was automatically generated by json-schema-to-typescript.
 * DO NOT MODIFY IT BY HAND. Instead, modify the source JSONSchema file,
 * and run \`CMS_PROVIDER=amplience pnpm cms:sync\` to regenerate this file.
 */

`

/**
 * Converts a schema filename to an output module basename.
 *
 * @param filename - Schema filename such as page-component-schema.json
 * @returns Output basename such as page-component
 */
const toOutputBasename = (filename) =>
  filename.replace(/-schema\.json$/, '').replace(/\.json$/, '')

/**
 * Converts a schema filename to a PascalCase interface name.
 *
 * @param filename - Schema filename such as page-component-schema.json
 * @returns Interface name such as PageComponent
 */
const toInterfaceName = (filename) =>
  toOutputBasename(filename)
    .split('-')
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join('')

/**
 * Converts a free-form title into a PascalCase identifier.
 *
 * Used to derive wrapper interface names from a content union member `title`
 * (e.g. "Rich Text" becomes `RichText`, "Smart Sorting Products" becomes `SmartSortingProducts`).
 *
 * @param title - Human-readable title from a schema node
 * @returns PascalCase identifier
 */
const toPascalCase = (title) =>
  title
    .split(/[^a-zA-Z0-9]+/)
    .filter(Boolean)
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join('')

/**
 * Builds a registry of every exported schema keyed by its `$id` URI.
 *
 * Each entry carries the local file path used to dereference the schema plus the generated
 * interface name and output basename used to rewrite cross-schema references into imports.
 * A single pass over the directory feeds both the dereference resolver and the ref rewriter,
 * so shared component types are defined once and reused instead of inlined into every container.
 *
 * @param dir - Directory containing exported Amplience schema bodies
 * @returns Map of schema URI to its file path, interface name, and output basename
 */
const buildSchemaRegistry = (dir) => {
  const registry = new Map()

  if (!fs.existsSync(dir)) {
    return registry
  }

  for (const file of fs.readdirSync(dir)) {
    if (!file.endsWith('.json')) {
      continue
    }

    const filePath = path.join(dir, file)
    const { $id } = JSON.parse(fs.readFileSync(filePath, 'utf8'))
    if ($id) {
      registry.set($id, {
        filePath,
        interfaceName: toInterfaceName(file),
        basename: toOutputBasename(file),
      })
    }
  }

  return registry
}

/**
 * Vendor core definitions that model a content relationship (a link to a separate content item)
 * rather than inline content. Both deliver the linked item, so they resolve to the same
 * component interface as an inline reference would.
 */
const CONTENT_RELATIONSHIP_REFS = new Set([
  // eslint-disable-next-line sonarjs/no-clear-text-protocols
  'http://bigcontent.io/cms/schema/v1/core#/definitions/content-link',
  // eslint-disable-next-line sonarjs/no-clear-text-protocols
  'http://bigcontent.io/cms/schema/v1/core#/definitions/content-reference',
])

/**
 * Resolves the component schema URI a content relationship (`content-link`/`content-reference`)
 * points at, if any.
 *
 * Amplience models a relationship as an `allOf` combining the vendor core definition with a
 * `contentType` enum that restricts which content type may be linked:
 *
 * ```json
 * {
 *   "allOf": [
 *     { "$ref": "http://bigcontent.io/cms/schema/v1/core#/definitions/content-link" },
 *     { "properties": { "contentType": { "enum": ["https://scayle.com/schemas/grid-component.json"] } } }
 *   ]
 * }
 * ```
 *
 * The linked item is delivered as the target component, so the relationship resolves to that
 * component's interface instead of inlining the raw link shape (which produced `Grid1`/`Section1`).
 *
 * @param node - Schema node to inspect
 * @param registry - Map of component schema URI to module info
 * @returns The linked component URI, or undefined when the node is not a content relationship
 */
const getContentRelationshipUri = (node, registry) => {
  if (!node || !Array.isArray(node.allOf)) {
    return undefined
  }

  const isRelationship = node.allOf.some(
    (member) =>
      typeof member?.$ref === 'string' &&
      CONTENT_RELATIONSHIP_REFS.has(member.$ref),
  )
  if (!isRelationship) {
    return undefined
  }

  for (const member of node.allOf) {
    const contentTypes = member?.properties?.contentType?.enum
    if (Array.isArray(contentTypes)) {
      const target = contentTypes.find((uri) => registry.has(uri))
      if (target) {
        return target
      }
    }
  }

  return undefined
}

/**
 * Resolves the component schema URI a node references, if any.
 *
 * Matches three shapes: a direct `{ $ref }`, the thin wrapper Amplience uses inside content
 * unions (a single-member `allOf` pointing at a component schema), and a content relationship
 * (`content-link`/`content-reference`) constrained to a single component `contentType`.
 *
 * @param node - Schema node to inspect
 * @param registry - Map of component schema URI to module info
 * @returns The referenced component URI, or undefined when the node is not a component ref
 */
const getComponentRefUri = (node, registry) => {
  if (!node || typeof node !== 'object') {
    return undefined
  }

  if (typeof node.$ref === 'string' && registry.has(node.$ref)) {
    return node.$ref
  }

  if (
    Array.isArray(node.allOf) &&
    node.allOf.length === 1 &&
    typeof node.allOf[0]?.$ref === 'string' &&
    registry.has(node.allOf[0].$ref)
  ) {
    return node.allOf[0].$ref
  }

  return getContentRelationshipUri(node, registry)
}

/**
 * Detects the "content wrapper" shape used by nested content unions.
 *
 * A wrapper is an object with a `componentType` discriminant (a string `const`) and exactly one
 * sibling property that references a component schema, for example:
 *
 * ```json
 * {
 *   "properties": {
 *     "componentType": { "const": "richText" },
 *     "richText": { "allOf": [{ "$ref": ".../rich-text-component.json" }] }
 *   }
 * }
 * ```
 *
 * These wrappers are identical across every container schema, so they are generated once in the
 * referenced component's own file instead of being inlined into each container.
 *
 * @param node - Schema node to inspect
 * @param registry - Map of component schema URI to module info
 * @returns Wrapper details (component URI, discriminant, property key, title), or undefined
 */
const getContentWrapperRef = (node, registry) => {
  if (!node || typeof node !== 'object' || node.type !== 'object') {
    return undefined
  }

  const props = node.properties
  if (!props || typeof props !== 'object') {
    return undefined
  }

  const componentType = props.componentType?.const
  if (typeof componentType !== 'string') {
    return undefined
  }

  const siblingKeys = Object.keys(props).filter(
    (key) => key !== 'componentType',
  )
  if (siblingKeys.length !== 1) {
    return undefined
  }

  const propKey = siblingKeys[0]
  const componentUri = getComponentRefUri(props[propKey], registry)
  if (!componentUri) {
    return undefined
  }

  return { componentUri, componentType, propKey, title: node.title }
}

/**
 * Scans every schema for content wrappers and records one canonical definition per component.
 *
 * The wrapper interface (e.g. `RichText`) is defined in the referenced component's file
 * (`rich-text-component.d.ts`) so containers can import it instead of each redeclaring it.
 * The first occurrence wins, which keeps the name stable across containers.
 *
 * @param files - Schema filenames to scan
 * @param registry - Map of component schema URI to module info
 * @returns Map of component schema URI to its wrapper definition
 */
const collectContentWrappers = (files, registry) => {
  const wrappers = new Map()

  const walk = (node) => {
    if (Array.isArray(node)) {
      node.forEach(walk)
      return
    }

    if (!node || typeof node !== 'object') {
      return
    }

    const wrapper = getContentWrapperRef(node, registry)
    if (wrapper && !wrappers.has(wrapper.componentUri)) {
      const target = registry.get(wrapper.componentUri)
      wrappers.set(wrapper.componentUri, {
        wrapperName: toPascalCase(wrapper.title ?? target.interfaceName),
        componentType: wrapper.componentType,
        propKey: wrapper.propKey,
        basename: target.basename,
        componentInterfaceName: target.interfaceName,
      })
    }

    for (const key of Object.keys(node)) {
      walk(node[key])
    }
  }

  for (const file of files) {
    walk(JSON.parse(fs.readFileSync(path.join(schemasDir, file), 'utf8')))
  }

  return wrappers
}

/**
 * Rewrites references to sibling component schemas into `tsType` placeholders.
 *
 * Without this, `$RefParser` inlines the referenced schema and json-schema-to-typescript
 * regenerates it (often with numeric-suffixed duplicates like `Text1` or `Divider1`).
 * Collapsing a reference (or its thin wrapper) to a `tsType` makes the union reference the
 * imported component type directly, so no intermediate alias like `Text = TextComponent` is
 * emitted. Vendor (`bigcontent.io`) references are left alone so they keep being inlined.
 *
 * @param node - Schema node to collapse in place
 * @param typeName - Interface name the node should resolve to
 * @param basename - Output basename that defines the interface
 * @param selfBasename - Output basename of the schema being generated (skips self-import)
 * @param imports - Accumulates module basename to the set of interface names to import
 */
const collapseToTsType = (node, typeName, basename, selfBasename, imports) => {
  // Replace the whole node (a $ref ignores siblings, and a wrapper only carries the
  // discriminant) so the imported type is used inline instead of via an alias.
  for (const key of Object.keys(node)) {
    delete node[key]
  }
  node.tsType = typeName

  if (basename !== selfBasename) {
    const names = imports.get(basename) ?? new Set()
    names.add(typeName)
    imports.set(basename, names)
  }
}

/**
 * @param node - Current schema node being visited
 * @param registry - Map of component schema URI to module info
 * @param selfBasename - Output basename of the schema being generated (skips self-import)
 * @param imports - Accumulates module basename to the set of interface names to import
 * @param wrappers - Map of component schema URI to its shared wrapper definition
 */
const rewriteComponentRefs = (
  node,
  registry,
  selfBasename,
  imports,
  wrappers,
) => {
  if (Array.isArray(node)) {
    for (const item of node) {
      rewriteComponentRefs(item, registry, selfBasename, imports, wrappers)
    }
    return
  }

  if (!node || typeof node !== 'object') {
    return
  }

  // Content wrapper -> reference the shared wrapper type from the component's own file.
  // Handled before descending so the inner component ref is not rewritten to a raw type.
  const wrapperRef = getContentWrapperRef(node, registry)
  const wrapper = wrapperRef && wrappers.get(wrapperRef.componentUri)
  if (wrapper) {
    collapseToTsType(
      node,
      wrapper.wrapperName,
      wrapper.basename,
      selfBasename,
      imports,
    )
    return
  }

  const componentUri = getComponentRefUri(node, registry)
  if (componentUri) {
    const target = registry.get(componentUri)
    collapseToTsType(
      node,
      target.interfaceName,
      target.basename,
      selfBasename,
      imports,
    )
    return
  }

  for (const key of Object.keys(node)) {
    rewriteComponentRefs(node[key], registry, selfBasename, imports, wrappers)
  }
}

/**
 * Builds `import type` statements for the component types referenced by a schema.
 *
 * @param imports - Map of module basename to the set of interface names to import
 * @returns Import block ending with a blank line, or an empty string when none are needed
 */
const buildImportBlock = (imports) => {
  if (imports.size === 0) {
    return ''
  }

  const lines = [...imports.entries()]
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([basename, names]) => {
      const named = [...names].sort().join(', ')
      return `import type { ${named} } from './${basename}'`
    })

  return `${lines.join('\n')}\n\n`
}

/**
 * Extracts the names of the top-level types and interfaces a module exports.
 *
 * Used to build deduplicated re-exports in the barrel file. `import type` lines are
 * ignored because they are not part of the module's public surface.
 *
 * @param source - Generated TypeScript source for a single module
 * @returns Ordered list of exported type and interface names
 */
const extractExportedNames = (source) => {
  const names = []
  const exportPattern = /^export (?:type|interface) (\w+)/gm
  let match

  while ((match = exportPattern.exec(source)) !== null) {
    names.push(match[1])
  }

  return names
}

const PRIMITIVE_TYPE = '(?:string|number|boolean|integer|unknown|null)'

/**
 * Checks whether a type expression is a primitive or union of primitives only.
 *
 * String-literal unions (enums) and complex shapes are excluded so they keep a
 * named export.
 *
 * @param rhs - Right-hand side of a generated `export type` alias
 * @returns `true` when the alias can be inlined
 */
const isSimplePrimitiveAlias = (rhs) => {
  let trimmed = rhs.trim()
  while (trimmed.startsWith('(') && trimmed.endsWith(')')) {
    trimmed = trimmed.slice(1, -1).trim()
  }

  if (/'[^']+'/.test(trimmed) || /"[^"]+"/.test(trimmed)) {
    return false
  }
  if (/[[({]/.test(trimmed)) {
    return false
  }

  return new RegExp(`^${PRIMITIVE_TYPE}(?: \\| ${PRIMITIVE_TYPE})*$`).test(
    trimmed,
  )
}

/**
 * Removes redundant `export type Name = string` aliases and inlines the primitive.
 *
 * json-schema-to-typescript names every titled property schema. For plain strings,
 * numbers, and booleans that produces noisy aliases such as `Label = string`.
 * Enum unions and complex types are left as named exports.
 *
 * @param source - Raw output from json-schema-to-typescript
 * @returns Source with simple primitive aliases collapsed
 */
const collapseSimpleTypeAliases = (source) => {
  const aliasPattern =
    /(\/\*\*[\s\S]*?\*\/\s*)?export type (\w+) = ([^\n;]+)\n/g
  const aliases = []
  let match

  while ((match = aliasPattern.exec(source)) !== null) {
    const [full, , name, rhs] = match
    if (!isSimplePrimitiveAlias(rhs)) {
      continue
    }

    let normalizedRhs = rhs.trim()
    while (normalizedRhs.startsWith('(') && normalizedRhs.endsWith(')')) {
      normalizedRhs = normalizedRhs.slice(1, -1).trim()
    }

    aliases.push({ name, rhs: normalizedRhs, full })
  }

  if (aliases.length === 0) {
    return source
  }

  let result = source
  for (const { full } of aliases) {
    result = result.replace(full, '')
  }

  for (const { name, rhs } of aliases) {
    result = result.replace(new RegExp(`\\b${name}\\b`, 'g'), rhs)
  }

  return result.replace(/\n{3,}/g, '\n\n')
}

/**
 * Dereferences an Amplience schema with local and vendor resolvers.
 *
 * @param schema - Schema object (already rewritten to keep sibling component refs as imports)
 * @param registry - Map of schema URI to its file path and module info
 * @returns Dereferenced JSON schema ready for TypeScript compilation
 */
const dereferenceSchema = async (schema, registry) => {
  if (!fs.existsSync(vendorCore)) {
    throw new Error(
      `Missing vendor schema at ${vendorCore}. Re-run cms:sync or restore the vendor file.`,
    )
  }

  return $RefParser.dereference(schema, {
    resolve: {
      bigcontent: {
        order: 1,
        canRead: (file) =>
          // eslint-disable-next-line sonarjs/no-clear-text-protocols
          file.url.startsWith('http://bigcontent.io/cms/schema/v1/core'),
        read: () => fs.readFileSync(vendorCore, 'utf8'),
      },
      scayle: {
        order: 2,
        canRead: (file) => file.url.startsWith('https://scayle.com/schemas/'),
        read: (file) => {
          const entry = registry.get(file.url)
          if (!entry) {
            throw new Error(`Unknown schema reference: ${file.url}`)
          }
          return fs.readFileSync(entry.filePath, 'utf8')
        },
      },
    },
  })
}

/**
 * Removes generated `.d.ts` files whose source schema no longer exists.
 *
 * The generator overwrites a file per schema but never deleted output for schemas that
 * were removed from the hub, leaving stale duplicated definitions behind. Pruning keeps
 * the `gen` directory in sync with the current schema export.
 *
 * @param generatedBasenames - Output basenames produced in the current run
 */
const pruneStaleDefinitions = (generatedBasenames) => {
  const expected = new Set(
    generatedBasenames.map((basename) => `${basename}.d.ts`),
  )

  for (const file of fs.readdirSync(outDir)) {
    if (file.endsWith('.d.ts') && !expected.has(file)) {
      fs.rmSync(path.join(outDir, file))
      console.log(`🗑️  Removed stale ${file} (no matching schema).`)
    }
  }
}

/**
 * Builds deduplicated named re-exports for the barrel file.
 *
 * Container schemas reuse helper names like `Content` or `Headline`, so a wildcard
 * `export *` would raise ambiguous re-export errors. Each name is re-exported from the
 * first module that defines it, keeping every unique type reachable without collisions.
 *
 * @param moduleExports - Per-module basename and exported type names, in generation order
 * @returns Newline-joined `export type { ... } from './module'` statements
 */
const buildBarrelExports = (moduleExports) => {
  const seen = new Set()

  return moduleExports
    .map(({ basename, names }) => {
      const unique = names.filter((name) => {
        if (seen.has(name)) {
          return false
        }
        seen.add(name)
        return true
      })

      if (unique.length === 0) {
        return ''
      }

      return `export type {\n  ${unique.join(',\n  ')},\n} from './${basename}'`
    })
    .filter(Boolean)
    .join('\n')
}

/**
 * Generates TypeScript definitions for all exported Amplience schema bodies.
 */
const generateAmplienceTypes = async () => {
  if (!fs.existsSync(schemasDir)) {
    console.warn(
      `⚠️  No schema bodies found at ${schemasDir}. Skipping type generation.`,
    )
    return
  }

  const schemaFiles = fs
    .readdirSync(schemasDir)
    .filter((file) => file.endsWith('.json'))
    .sort()

  if (schemaFiles.length === 0) {
    console.warn(
      `⚠️  No schema JSON files found in ${schemasDir}. Skipping type generation.`,
    )
    return
  }

  const registry = buildSchemaRegistry(schemasDir)
  const wrappers = collectContentWrappers(schemaFiles, registry)
  fs.mkdirSync(outDir, { recursive: true })

  const moduleExports = []

  for (const schemaFile of schemaFiles) {
    const interfaceName = toInterfaceName(schemaFile)
    const outputBasename = toOutputBasename(schemaFile)

    console.log(`🔧 Generating ${outputBasename}.d.ts from ${schemaFile}...`)

    const rawSchema = JSON.parse(
      fs.readFileSync(path.join(schemasDir, schemaFile), 'utf8'),
    )
    const schemaId = rawSchema.$id
    const imports = new Map()
    rewriteComponentRefs(rawSchema, registry, outputBasename, imports, wrappers)

    const dereferenced = await dereferenceSchema(rawSchema, registry)
    const compiled = await compile(
      { ...dereferenced, title: interfaceName },
      interfaceName,
      {
        bannerComment: '',
        format: false,
        unknownAny: true,
        // Emit content arrays as `T[]` instead of expanding bounded arrays into
        // positional tuple unions (e.g. `[] | [T] | [T, T] | ...`). The `@minItems`
        // and `@maxItems` constraints are still kept as JSDoc on the array.
        maxItems: -1,
      },
    )

    const cleaned = collapseSimpleTypeAliases(compiled)
    // Append the shared wrapper interface when this component is used inside a content union.
    const wrapper = wrappers.get(schemaId)
    const body = wrapper
      ? `${cleaned}
/**
 * Content array entry pairing the \`${wrapper.componentType}\` discriminant with its ${wrapper.componentInterfaceName} payload.
 */
export interface ${wrapper.wrapperName} {
  componentType: '${wrapper.componentType}'
  ${wrapper.propKey}?: ${wrapper.componentInterfaceName}
  _meta?: {
    deliveryId?: string
    deliveryKey?: string
  }
  [k: string]: unknown
}
`
      : cleaned

    await writeFormattedFile(
      path.join(outDir, `${outputBasename}.d.ts`),
      `${BANNER}${buildImportBlock(imports)}${body}`,
    )
    moduleExports.push({
      basename: outputBasename,
      names: extractExportedNames(body),
    })
  }

  pruneStaleDefinitions(moduleExports.map(({ basename }) => basename))

  const indexPath = path.join(outDir, 'index.ts')
  const indexContents = `/**
 * Amplience content-type TypeScript definitions.
 *
 * Component types below are generated from exported JSON schemas via
 * \`CMS_PROVIDER=amplience pnpm cms:sync\`.
 *
 * Baseline types cover content types not yet exported from your hub.
 */

${buildBarrelExports(moduleExports)}

/** Amplience delivery metadata attached to every content item. */
export interface AmplienceMeta {
  /** Schema URI identifying the content type */
  schema?: string
  /** Stable delivery identifier for visualization annotations */
  deliveryId?: string
  /** Delivery key when set on the content item */
  deliveryKey?: string
}

/** Base shape for Amplience delivery responses with optional nested content wrapper. */
export type AmplienceContentItem<T = Record<string, unknown>> = T & {
  _meta?: AmplienceMeta
  content?: unknown
  [key: string]: unknown
}

/** Dynamic Media image link delivered by Amplience. */
export interface AmplienceImageLink {
  /** Media CDN host */
  defaultHost: string
  /** Media endpoint identifier */
  endpoint: string
  /** Asset name within the endpoint */
  name: string
}
`

  await writeFormattedFile(indexPath, indexContents)
  console.log(
    `✅ Generated ${moduleExports.length} Amplience type definition(s).`,
  )
}

generateAmplienceTypes().catch((error) => {
  console.error('❌ Failed to generate Amplience types:', error)
  process.exit(1)
})
